#!/bin/sh
# Build `scripts/provision-sink.sh` -- the ONE run-script payload the `sink`
# node installs (work order §5 E2/E8).
#
# corp-twin's copy of `twin-configs/svc-engines/scripts/build-sink-payload.sh`
# (a twin never reaches into another twin's folder -- WORK_ORDER_twin_
# consolidation.md §2), same logic, same corpus source: the corpapcn-disco
# cast's `topology.json`, which is the observed external world of THIS network
# (docs/WORK_ORDER_corp_twin.md §7). When Phase 2 migrates that cast to
# `twins/pit-395a61f04e-1780405200/generated/topology.json`, pass that path as
# $1 (or repoint the default below) -- the file is the input, not a dependency
# on the other twin's folder layout.
#
# **Why this exists at all.** The sink needs two payloads in the guest, in
# order: the GENERATED corpus (`scripts/gen_sink_corpus.py`'s
# `install-sink-corpus.sh`, which writes `/etc/axr-sink/db.axr-sink-root` +
# `external-cidrs.txt`) and then the SHARED recipe
# (`twins/_shared/scripts/serve-sink.sh`, which fails loud when the
# corpus is absent). The generator's own docstring says *"a twin declares them
# as two `install:` actions in that order"* -- but the planner does not allow
# that: `pass1_emit._emit_apps` refuses a second `script:` action per app
# (*"the config slice supports one script: per app (multiple is a
# fast-follow)"*), and a twin config synthesizes exactly one app per node. So
# the two are concatenated into one payload here, at authoring time, rather
# than worked around in the twin config.
#
# That mismatch is worth someone's attention rather than just this workaround:
# either `_emit_apps` grows multi-script support, or the sink's corpus becomes
# a `pkg:`-style data action. Until then, this script IS the seam.
#
# **Deterministic.** The generator emits byte-identical files for the same
# topology (its own property, asserted by `tests/test_sink_corpus.py`), and
# concatenation adds nothing time- or host-dependent, so re-running this
# produces the same payload and therefore the same `plan_id`.
#
# **Regenerate it whenever** the cast topology changes, `serve-sink.sh`
# changes, or you want a different external world. `te plan` fails loudly if
# `provision-sink.sh` is missing, which is the intended reminder.
#
# Usage (from anywhere):
#     sh twins/corp-twin/scripts/build-sink-payload.sh [topology.json]
set -eu

_here="$(cd "$(dirname "$0")" && pwd)"
_repo="$(cd "$_here/../../.." && pwd)"
_topology="${1:-$_repo/twins/pit-395a61f04e-1780405200/generated/pit-395a61f04e-1780405200.topology.json}"
_serve="$_repo/twins/_shared/scripts/serve-sink.sh"
_out="$_here/provision-sink.sh"
_tmp="$(mktemp -d)"
trap 'rm -rf "$_tmp"' EXIT

_py="$_repo/.venv/bin/python"
[ -x "$_py" ] || _py="python3"

[ -f "$_topology" ] || { echo "build-sink-payload: no topology at $_topology" >&2; exit 1; }
[ -f "$_serve" ] || { echo "build-sink-payload: no serve-sink.sh at $_serve (is the E2 slice in?)" >&2; exit 1; }

"$_py" "$_repo/scripts/gen_sink_corpus.py" --topology "$_topology" --out "$_tmp"

[ -s "$_tmp/install-sink-corpus.sh" ] \
    || { echo "build-sink-payload: the generator wrote no install-sink-corpus.sh" >&2; exit 1; }

{
    echo "#!/bin/sh"
    echo "# GENERATED by twins/corp-twin/scripts/build-sink-payload.sh --"
    echo "# do not hand-edit. It is the concatenation, in this order, of:"
    echo "#   1. install-sink-corpus.sh  (scripts/gen_sink_corpus.py, from"
    echo "#      $(basename "$(dirname "$_topology")")/$(basename "$_topology"))"
    echo "#   2. twins/_shared/scripts/serve-sink.sh  (shared, hand-written)"
    echo "# Two files because run-script (OP-APP-030) delivers ONE script per app;"
    echo "# see build-sink-payload.sh's header for why that is a seam, not a style."
    echo "#"
    echo "# NOTE: \`provision-sink.sh --healthcheck\` re-writes the corpus files"
    echo "# (idempotent) before reaching serve-sink.sh's healthcheck branch."
    echo ""
    cat "$_tmp/install-sink-corpus.sh"
    echo ""
    cat "$_serve"
} > "$_out"
chmod 0755 "$_out"

_records="$(grep -c ' IN A' "$_tmp/db.axr-sink-root" || true)"
_cidrs="$(grep -c '^[0-9]' "$_tmp/external-cidrs.txt" || true)"
_bytes="$(wc -c < "$_out" | tr -d ' ')"
# What actually travels is the base64 of the payload, as ONE `agent/exec`
# command argument. PVE refuses an argument >= 131072 bytes (measured, dev45 /
# PVE 9.2, 2026-09-21: it fails as `HTTP 596 Broken pipe` with no error body).
# `GuestAgent.write_file` chunks past that now, so this is a warning and not a
# hard gate -- but a payload that needs chunking is a payload worth a look.
_b64="$(( (_bytes + 2) / 3 * 4 ))"
echo "build-sink-payload: $_out"
echo "  dns records : $_records"
echo "  cidrs       : $_cidrs"
echo "  payload     : $_bytes bytes ($_b64 as base64, the QGA per-argument"
echo "                ceiling is 131071 -- corpus files travel gzip+base64)"
if [ "$_b64" -ge 131072 ]; then
    echo "  NOTE: over the per-argument ceiling; delivery will be chunked" >&2
fi
